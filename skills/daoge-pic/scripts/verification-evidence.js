const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

/**
 * Regenerates the machine-produced evidence block in docs/vnext_verification_evidence_zh.md from a real
 * build and a real regression run, so release notes cannot drift away from the code again.
 *
 *   node scripts/verification-evidence.js                  # rewrite the block
 *   node scripts/verification-evidence.js --check           # fail when the block is stale
 *   node scripts/verification-evidence.js --with-package    # also run the package smoke
 */

const BEGIN = '<!-- verification:worktree:begin';
const END = '<!-- verification:worktree:end -->';
const DOC = path.join(__dirname, '..', 'docs', 'vnext_verification_evidence_zh.md');
const workspace = path.join(__dirname, '..');

const withPackage = process.argv.includes('--with-package');
const checkOnly = process.argv.includes('--check');

function run(command, args, label) {
  const result = spawnSync(command, args, { cwd: workspace, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' });
  const output = String(result.stdout || '') + String(result.stderr || '');
  if (result.status !== 0) {
    process.stderr.write('[' + label + '] failed with exit code ' + result.status + '\n');
    process.stderr.write(output.split('\n').slice(-40).join('\n') + '\n');
    process.exit(1);
  }
  return output;
}

function regressionFiles() {
  const directory = path.join(workspace, 'tests', 'vnext');
  return fs.readdirSync(directory).filter((name) => name.endsWith('.test.js')).sort().map((name) => path.join('tests', 'vnext', name));
}

function workbenchChunkLabels() {
  const assets = path.join(workspace, 'dist', 'workbench', 'assets');
  return fs.readdirSync(assets)
    .filter((name) => /^index-.*\.(js|css)$/.test(name))
    .sort()
    .map((name) => name.split('.').pop().toUpperCase() + ' ' + (fs.statSync(path.join(assets, name)).size / 1000).toFixed(2) + ' kB');
}

const buildOutput = run('npm', ['run', 'build'], 'npm run build');
const modules = /(\d+) modules transformed/.exec(buildOutput);
const chunks = workbenchChunkLabels();
const regressionOutput = run(process.execPath, ['--test', '--test-concurrency=1', ...regressionFiles()], 'node --test');
const counts = {};
for (const key of ['tests', 'pass', 'fail', 'cancelled', 'skipped', 'todo']) {
  const match = new RegExp('^# ' + key + ' (\\d+)$', 'm').exec(regressionOutput);
  counts[key] = match ? Number(match[1]) : null;
}
if (counts.tests === null || counts.pass === null) {
  process.stderr.write('regression run did not emit a TAP summary; refusing to write evidence.\n');
  process.exit(1);
}

const lines = [
  '- 生成时间：`' + new Date().toISOString() + '`（Node.js `' + process.version + '`，`' + process.platform + '`）。',
  '- `npm run build`：通过；Vite 转换 ' + (modules ? modules[1] : '未知') + ' 个模块，Workbench 产物 ' + chunks.join('、') + '，只有非阻断大小提示。',
  '- 全量回归：`node --test --test-concurrency=1 tests/vnext/*.test.js` 共 ' + counts.tests + ' 项，`' + counts.pass + ' 通过`、`' + counts.fail + ' 失败`、`' + counts.cancelled + ' 取消`、`' + counts.skipped + ' 条件跳过`、`' + counts.todo + ' 待办`。'
];
if (withPackage) {
  const packageOutput = run('npm', ['run', 'test:package'], 'npm run test:package');
  const listed = /(\d+) 个文件|(\d+) files/.exec(packageOutput);
  lines.push('- `npm run test:package`：通过；发布清单 ' + (listed ? (listed[1] || listed[2]) + ' 个文件' : '已检查') + '，`unexpected=0`、`maps=0`、`retired=0`、`sensitive=0`；临时安装、真实 bin、help、register-skill、doctor 与 `sharp` 均通过。');
}
if (counts.fail !== 0) lines.push('- 注意：本次回归存在失败项，该结果不得作为冻结证据。');

const block = [
  BEGIN + ' - generated by scripts/verification-evidence.js, do not edit by hand; run `npm run verify:evidence` -->',
  ...lines,
  END
].join('\n');

const document = fs.readFileSync(DOC, 'utf8');
const beginIndex = document.indexOf(BEGIN);
const endIndex = document.indexOf(END);
if (beginIndex < 0 || endIndex < 0 || endIndex < beginIndex) {
  process.stderr.write('evidence markers are missing from ' + DOC + '; refusing to write.\n');
  process.exit(1);
}
const existing = document.slice(beginIndex, endIndex + END.length).trimEnd();
const next = document.slice(0, beginIndex) + block + document.slice(endIndex + END.length);

if (checkOnly) {
  const stable = (value) => value.replace(/^- 生成时间：.*$/m, '');
  if (stable(existing) !== stable(block)) {
    process.stderr.write('verification evidence block is stale; run `npm run verify:evidence`.\n');
    process.stderr.write('expected:\n' + block + '\n\nfound:\n' + existing + '\n');
    process.exit(1);
  }
  process.stdout.write('verification evidence block is current.\n');
  process.exit(0);
}

fs.writeFileSync(DOC, next);
process.stdout.write(block + '\n');
